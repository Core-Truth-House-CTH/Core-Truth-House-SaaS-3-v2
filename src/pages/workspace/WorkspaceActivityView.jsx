import { useMemo, useState } from "react";
import { BarChart3, CalendarClock, Search, ShieldCheck } from "lucide-react";
import { Empty, Pill } from "./WorkspacePrimitives";
import { formatDateTime } from "./workspaceRoutes";

export default function WorkspaceActivityView({ data }) {
  const [query, setQuery] = useState("");
  const filtered = useMemo(() => data.activity.filter((item) =>
    `${item.actor} ${item.role} ${item.action} ${item.module} ${item.detail}`
      .toLowerCase()
      .includes(query.toLowerCase())
  ), [data.activity, query]);

  if (!data.companionAvailable) {
    const summary = data.activitySummary || {};
    const items = [
      ["AI credits used", summary.total_credits_used ?? 0],
      ["Content generated", summary.content_generated ?? 0],
      ["Active contributors", Object.keys(summary.credits_by_member || {}).length],
    ];
    return (
      <article className="ws-panel">
        <div className="ws-panel-head"><div><h2>Workspace Activity</h2><p>The companion event stream is unavailable, so this page shows only the verified team summary.</p></div><Pill tone="gold">Summary</Pill></div>
        <div className="ws-stat-grid">{items.map(([label, value]) => <div key={label}><BarChart3 size={18} /><strong>{value}</strong><span>{label}</span></div>)}</div>
        <div className="ws-privacy-card"><ShieldCheck size={18} /><div><strong>No fabricated timeline</strong><p>Chronological events appear only after the tenant activity endpoint answers.</p></div></div>
      </article>
    );
  }

  return (
    <article className="ws-panel">
      <div className="ws-panel-head"><div><h2>Workspace Activity</h2><p>Tenant-scoped events generated by Workspace controls and lifecycle actions.</p></div><Pill tone="green">{data.activity.length} events</Pill></div>
      <label className="ws-search-field"><Search size={16} /><input value={query} onChange={(event) => setQuery(event.target.value)} placeholder="Search member, action, or module" /></label>
      {filtered.length ? <div className="ws-timeline">{filtered.map((item) => (
        <div key={item.id} className="ws-timeline-event">
          <time>{formatDateTime(item.createdAt)}</time>
          <span className="ws-timeline-dot" />
          <div>
            <strong>{item.actor} · {item.action.replaceAll("_", " ")}</strong>
            <p>{item.detail || item.module.replaceAll("_", " ")}</p>
            <div className="ws-asset-meta"><span>{item.role}</span><span>{item.module.replaceAll("_", " ")}</span></div>
          </div>
        </div>
      ))}</div> : <Empty icon={CalendarClock} title="No matching activity" description="New Workspace control and lifecycle events will appear here." />}
    </article>
  );
}
